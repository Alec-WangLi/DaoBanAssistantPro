// 「现在」的唯一入口。
//
// 为什么要有这个文件：日历页拿「今天」决定**显示哪一个月**、哪一格高亮、
// 「本月统计」统计哪个月 —— 这些判据原先散落着直接调 `DateTime.now()`，
// 于是界面行为随真实日期漂移，而测试又拿真实日期去算期望值，两边一起漂。
//
// 2026-11-05 那次就是这个形态：10 条用例一起红，根因是「11 月」这个月份本身 ——
// 无法定节假日（徽章画不出来）、只有 30 天（`day-card-31` 不存在）、且是**6 行月**
// （网格比 5 行月高一行，`_scrollRoom` 从 0 变成 1.0 / 21.0）。
// 把锚点钉死在某一个月只是治标：只要页面还读系统时钟，测试钉的是 A 月、界面画的
// 是 B 月，照样红。
//
// 用法：生产代码一律 `appNow()`；测试里
//   setUp(() => appNow = () => kAnchor);
//   tearDown(() => appNow = DateTime.now);
// 它是**模块级**状态，用完必须还原，否则会漏到同一个测试文件的下一个用例
// （与 `L10n.locale` / `liquidGlassActive` 同一条纪律）。

