// 测试共用：「这段文案里还有中文吗」的判定。
//
// 英文界面下漏出中文是本项目的一类反复出现的缺陷（模板标题、班次名、
// 分组标题、班组名都栽过），所以这条判定被三个测试文件共用 —— 各写一份
// 迟早会有一份漏掉某个码点区间。

/// 是否含中英之外的表意文字 / 中文标点 / 全角符号。
///
/// 用码点区间判定而不写字面汉字：免得测试文件本身被当成「有中文」的噪音，
/// 也免得那几个字面字符在复制粘贴中被改坏。`·`（U+00B7）与 `–`（U+2013）
/// 都不在区间内，因此英文文案里用它们是合法的。
bool hasCjk(String s) {
  for (final r in s.runes) {
    if ((r >= 0x3000 && r <= 0x303F) ||
        (r >= 0x4E00 && r <= 0x9FFF) ||
        (r >= 0xFF00 && r <= 0xFFEF)) {
      return true;
    }
  }
  return false;
}
